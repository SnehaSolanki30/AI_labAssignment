package MyJavaFolder.Day2;

public class LogicalOp {
    public static void main(String args[]){
    
            int A = 10;
            int B = 5;
    
          //logical AND 
          System.out.println((A > B) && (A < 20));

          //logical OR 
          System.out.println((A < B) || (A > 20));

            //logical NOT 
            System.out.println(!(A > B));
        }
    
}
