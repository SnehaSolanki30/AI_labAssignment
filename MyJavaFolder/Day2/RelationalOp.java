package MyJavaFolder.Day2;

public class RelationalOp {
    public
    static void main(String args[]){
    
            int A = 10;
            int B = 5;
    
          //equal to 
          System.out.println((A == B));

          //not equal to
          System.out.println((A != B));

            //greater than
            System.out.println((A > B));

            //less than
            System.out.println((A < B));

            //greater than or equal to
            System.out.println((A >= B));   


            //less than or equal to
            System.out.println((A <= B));



        }
}
