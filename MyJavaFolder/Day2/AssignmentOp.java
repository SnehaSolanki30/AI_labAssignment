package MyJavaFolder.Day2;

public class AssignmentOp {
    public static void main(String args[]){
    
            int A = 10;
            int B = 5;
    
            //Assignment
            System.out.println(A = B);

            //Add
            System.out.println(A += B);

            //Subtract 
            System.out.println(A -= B);

            //Multiply
            System.out.println(A *= B);

            //Divide
            System.out.println(A /= B);

            //Modulus
            System.out.println(A %= B);
        }
}
